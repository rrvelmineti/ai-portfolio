"""How each fictional client's extract differs (all names and plans are invented).

A column is ``(header, target)`` where ``target`` is a dictionary field, or an ``extra:``
kind for a column that maps to nothing (``member_name``, ``address``, ``group``, ...).
"""

from __future__ import annotations

from dataclasses import dataclass, field

from claims_onboarding.synthetic.formats import FileFormat

# (target field, kind of planted error) -> rule text is derived in generate.py
ErrorPlan = dict[tuple[str, str], int]


@dataclass(frozen=True)
class Client:
    number: int
    code: str
    name: str
    fmt: FileFormat
    date_format: str
    amount_style: str  # "plain" | "currency"
    status_case: str  # "lower" | "upper" | "title"
    columns: tuple[tuple[str, str], ...]
    claim_id: str  # format string with {n}
    member_id: str  # format string with {n}
    rows_week1: int
    rows_week2: int
    errors_week1: ErrorPlan
    week2_rename: tuple[str, str]  # (old header, new header)
    week2_new_column: tuple[str, str]  # (header, extra kind)
    faker_locale: str = "en_US"
    legacy: bool = False  # client 1: week 1 is the ported original sample
    notes: tuple[str, ...] = field(default_factory=tuple)

    @property
    def slug(self) -> str:
        return f"client_{self.number:02d}_{self.code.lower()}"

    def mapped(self) -> dict[str, str]:
        """target field -> header."""
        return {t: h for h, t in self.columns if not t.startswith("extra:")}


CSV = FileFormat()
